-- Run this entire file once in Supabase Dashboard -> SQL Editor.
-- It stores transcripts and structured text only. No audio is stored here.

create table if not exists public.recordings (
    audio_hash text primary key,
    transcript text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.items (
    id bigint generated by default as identity primary key,
    recording_hash text not null references public.recordings(audio_hash) on delete cascade,
    item_type text not null check (item_type in ('task', 'appointment', 'memory')),
    title text not null,
    summary text,
    transcript text not null,
    due text,
    start text,
    tags text[] not null default '{}',
    created_at timestamptz not null default now()
);

create index if not exists items_created_at_idx on public.items (created_at desc);
create index if not exists items_type_idx on public.items (item_type);

create table if not exists public.questions (
    id bigint generated by default as identity primary key,
    question text not null,
    answer text not null,
    created_at timestamptz not null default now()
);

-- Enable Row Level Security. No anon/authenticated policies are created;
-- only the server-side secret/service-role key should access these tables.
alter table public.recordings enable row level security;
alter table public.items enable row level security;
alter table public.questions enable row level security;

grant all on table public.recordings to service_role;
grant all on table public.items to service_role;
grant all on table public.questions to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Atomic and idempotent insert: if an ESP32 upload is retried, the same
-- recording hash is not inserted a second time.
create or replace function public.save_note_recording(
    p_audio_hash text,
    p_transcript text,
    p_created_at timestamptz,
    p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    inserted_count integer;
begin
    insert into public.recordings (audio_hash, transcript, created_at)
    values (p_audio_hash, p_transcript, p_created_at)
    on conflict (audio_hash) do nothing;

    get diagnostics inserted_count = row_count;
    if inserted_count = 0 then
        return jsonb_build_object('duplicate', true);
    end if;

    insert into public.items (
        recording_hash, item_type, title, summary, transcript,
        due, start, tags, created_at
    )
    select
        p_audio_hash,
        coalesce(entry.item->>'type', 'memory'),
        coalesce(entry.item->>'title', left(p_transcript, 70)),
        coalesce(entry.item->>'summary', p_transcript),
        p_transcript,
        nullif(entry.item->>'due', 'null'),
        nullif(entry.item->>'start', 'null'),
        coalesce(
            array(select jsonb_array_elements_text(coalesce(entry.item->'tags', '[]'::jsonb))),
            '{}'::text[]
        ),
        p_created_at
    from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) as entry(item);

    return jsonb_build_object('duplicate', false);
end;
$$;

revoke all on function public.save_note_recording(text, text, timestamptz, jsonb) from public;
revoke all on function public.save_note_recording(text, text, timestamptz, jsonb) from anon, authenticated;
grant execute on function public.save_note_recording(text, text, timestamptz, jsonb) to service_role;
